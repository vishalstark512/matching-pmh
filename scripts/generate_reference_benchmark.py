#!/usr/bin/env python3
"""Write docs/benchmarks/*.md reference tables (metrics only — no raw data).

Uses synthetic Office-31-style features by default. For real Office-31:

  python scripts/generate_reference_benchmark.py \\
    --office31-root /path/outside/repo/office31 \\
    --output docs/benchmarks/office31_amazon_to_dslr.md
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--office31-root", type=str, default=None)
    parser.add_argument("--source", type=str, default="amazon")
    parser.add_argument("--target", type=str, default="dslr")
    parser.add_argument("--rank", type=int, default=None, help="Default 32 for Office-31, 16 synthetic")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--max-samples", type=int, default=None, help="Cap per domain (Office-31: all images if unset)")
    parser.add_argument("--n-target-pool", type=int, default=200)
    parser.add_argument("--n-test", type=int, default=250)
    parser.add_argument("--n-train-src", type=int, default=1500)
    parser.add_argument("--legacy-split", action="store_true", help="Use random 70/30 split (buggy; not for Office-31)")
    parser.add_argument(
        "--output",
        type=str,
        default="docs/benchmarks/office31_synthetic_reference.md",
    )
    args = parser.parse_args()

    rank = args.rank
    preset_name = "t1_office31_sklearn" if args.office31_root else "t1_synthetic_sklearn"
    from pmh.benchmark.presets import get_preset

    preset = get_preset(preset_name)
    bench_kw: dict = {
        "include_coral": True,
        "seed": args.seed,
        **preset.sklearn_benchmark,
        "paper_protocol": not args.legacy_split,
    }

    if args.office31_root:
        from pmh.datasets.office31 import extract_office31_features

        rank = rank if rank is not None else preset.default_rank
        protocol = (
            f"Office-31 ResNet-18 features: {args.source} -> {args.target} "
            f"(preset={preset_name}, pool={args.n_target_pool}, test={args.n_test}, rank={rank})"
        )
        x_src, y_src = extract_office31_features(
            args.office31_root,
            args.source,
            max_samples=args.max_samples,
            seed=args.seed,
        )
        x_tgt, y_tgt = extract_office31_features(
            args.office31_root,
            args.target,
            max_samples=args.max_samples,
            seed=args.seed + 1,
        )
        bench_kw.update(
            n_train_src=args.n_train_src,
            n_target_pool=args.n_target_pool,
            n_test=args.n_test,
        )
    else:
        from pmh.benchmark.sklearn_protocol import synthetic_office31_features

        rank = rank if rank is not None else 16
        protocol = "Synthetic Office-31-style shift (bundled protocol; not raw images)"
        n = 600 if args.max_samples is None else min(args.max_samples, 600)
        x_src, y_src, x_tgt, y_tgt = synthetic_office31_features(n=n, seed=args.seed, d=128)

    from pmh import compare_arms_sklearn
    from pmh.benchmark.report import benchmark_to_markdown

    result = compare_arms_sklearn(
        x_src,
        y_src,
        x_tgt,
        y_tgt,
        preset=preset_name,
        rank=rank,
        **{k: v for k, v in bench_kw.items() if k not in ("rank",)},
    )

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    meta = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "protocol": protocol,
        "preset": preset_name,
        "rank": rank,
        "seed": args.seed,
        "paper_protocol": not args.legacy_split,
        "note": "Metrics only. No features or images stored in git.",
    }
    body = benchmark_to_markdown(
        result.to_dict(),
        title=f"Reference benchmark ({protocol})",
    )
    status = (
        f"> **Preset:** `{preset_name}`. "
        f"{'T1 paper_protocol (pool/test split, rank 32).' if meta['paper_protocol'] else 'Legacy random split — not for Office-31.'} "
        "Do **not** cite pre-2026-05-19 tables with B0 ≈ 0.7 / rank 16. "
        "See [CORRECT_USAGE.md](../CORRECT_USAGE.md).\n\n"
    )
    header = (
        "<!-- AUTO-GENERATED by scripts/generate_reference_benchmark.py -->\n"
        "<!-- Do not commit datasets or .npy files. Regenerate locally. -->\n\n"
        f"{status}"
        f"```json\n{json.dumps(meta, indent=2)}\n```\n\n"
    )
    out_path.write_text(header + body, encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
